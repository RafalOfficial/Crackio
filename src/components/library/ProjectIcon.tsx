/** An uploaded .svg ("svg:<base64>"), drawn as a mask in the current text color. */
export function SvgGlyph({ icon, size }: { icon: string; size: number }) {
  return <span className="project-svg block" style={{ width: size, height: size, "--svg": `url("data:image/svg+xml;base64,${icon.slice(4)}")` } as CSSProperties} />;
}

/** General's own mark: everything that isn't filed in a project. */
export const GENERAL_ICON = "general";
export const GENERAL_COLOR = "#bdb9b3";

/**
 * A project's icon in its color. `tile` sets it on a quiet tinted squircle (like a tool mark);
 * without it, it's just the glyph, for menus and inline names. Any color reads on the dark UI:
 * very dark picks are lifted just enough to see (globals.css, "Library projects").
 */
export function ProjectIcon({ icon, color, size = 16, tile = false, className }: { icon: string; color: string; size?: number; tile?: boolean; className?: string }) {
  const glyph = tile ? Math.round(size * 0.52) : size;
  const Glyph = icon === GENERAL_ICON ? LayoutGrid : (ICON_GLYPHS[icon as ProjectIconId] ?? Folder);
  const mark = isCustomIcon(icon) ? <SvgGlyph icon={icon} size={glyph} /> : <Glyph size={glyph} strokeWidth={2} />;
  return (
    <span
      aria-hidden="true"
      className={cn("project-tint inline-grid shrink-0 place-items-center", tile ? "project-tile squircle" : "project-glyph", className)}
      style={{ "--hue": color, ...(tile ? { width: size, height: size, borderRadius: Math.round(size * 0.32) } : null) } as CSSProperties}
    >
      {mark}
    </span>
  );
}
